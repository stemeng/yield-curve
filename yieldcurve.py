from ecbdata import ecbdata
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.ticker import PercentFormatter

# Anno corrente: si aggiorna automaticamente
anno = pd.Timestamp.now(tz="Europe/Rome").year
inizio = f"{anno}-01-01"

# Rendimenti par dei titoli di Stato AAA dell'area euro
serie = "YC.B.U2.EUR.4F.G_N_A.SV_C_YM.PY_"

curve = []

for scadenza in range(1, 31):
    df = ecbdata.get_series(
        f"{serie}{scadenza}Y",
        start=inizio
    )

    df["TIME_PERIOD"] = pd.to_datetime(df["TIME_PERIOD"])
    df["OBS_VALUE"] = pd.to_numeric(df["OBS_VALUE"], errors="coerce")

    s = (
        df.set_index("TIME_PERIOD")["OBS_VALUE"]
        .rename(scadenza)
    )
    curve.append(s)

# Mantiene solo date con dati per tutte le scadenze
dati = pd.concat(curve, axis=1).sort_index()
dati = dati.loc[dati.index.year == anno].dropna()

if dati.empty:
    raise ValueError(
        f"Non ci sono ancora curve complete disponibili per il {anno}."
    )

data_inizio = dati.index[0]
data_ultima = dati.index[-1]

# Chart
fig, ax = plt.subplots(figsize=(11, 6))

ax.plot(
    dati.columns,
    dati.iloc[0],
    color="#969696",
    linestyle="--",
    linewidth=2.5,
    label=f"Start of year — {data_inizio:%d %b %Y}"
)

ax.plot(
    dati.columns,
    dati.iloc[-1],
    color="#1255A2",
    linewidth=3,
    label=f"Latest available — {data_ultima:%d %b %Y}"
)

ax.set_title(
    "Yield Curve",
    fontsize=17,
    fontweight="bold",
    loc="left",
    pad=30
)

ax.text(
    0, 1.025,
    "Euro Area AAA-Rated Government Bonds · Par Yields",
    transform=ax.transAxes,
    fontsize=11,
    color="#555555"
)

ax.set_xlabel("Maturity (years)", fontsize=11)
ax.set_ylabel("Annual yield (%)", fontsize=11)
ax.set_xticks([1, 5, 10, 15, 20, 25, 30])
ax.set_xlim(1, 30)
ax.yaxis.set_major_formatter(PercentFormatter(xmax=100))

ax.grid(axis="y", alpha=0.2)
ax.spines[["top", "right"]].set_visible(False)
ax.legend(frameon=False, loc="best")

fig.text(
    0.08, 0.025,
    f"Source: ECB · Latest observation: {data_ultima:%d %b %Y}",
    fontsize=9,
    color="#666666"
)

fig.tight_layout(rect=[0, 0.06, 1, 1])

fig.savefig(
    "yield_curve.png",
    dpi=200,
    bbox_inches="tight",
    facecolor="white"
)

plt.show()